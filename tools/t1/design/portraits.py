def svg_group(name, x=0, y=0, sc=1.0, flip=False):
    items = ALL[name]; out = []
    for d, fill, sw, st in items:
        f = fill if fill else 'none'
        s = f' stroke="{st}" stroke-width="{sw}"' if sw else ''
        out.append(f'<path d="{d}" fill="{f}"{s} stroke-linejoin="round" stroke-linecap="round"/>')
    tf = f'translate({x + (200 * sc if flip else 0)},{y}) scale({-sc if flip else sc},{sc})'
    return f'<g transform="{tf}">' + ''.join(out) + '</g>'

def export_js():
    import json
    return json.dumps({k: [[d, f, sw, st] for d, f, sw, st in v] for k, v in ALL.items()}, ensure_ascii=False)

